#!/usr/bin/env ruby
# Convert a JIS X 0208 16x16 BDF font plus the JIS0208.TXT mapping into a C
# header: glyph bitmaps sorted by Unicode code point, and a parallel array of
# the code points for a binary search.
#
#   ruby jisfont2c.rb shnmk16.bdf JIS0208.TXT font_jis16.h
#
# Each glyph is 16 rows of 2 bytes, MSB = leftmost pixel.

bdf, table, dst = ARGV
abort "usage: jisfont2c.rb <font.bdf> <JIS0208.TXT> <out.h>" unless bdf && table && dst

glyphs = {}   # jis code => [16 row words]
encoding = nil
rows = nil
File.foreach(bdf) do |line|
  case line
  when /\AENCODING (\d+)/
    encoding = $1.to_i
  when /\ABBX (\d+) (\d+)/
    abort "#{bdf}: glyph #{encoding} is #{$1}x#{$2}, expected 16x16" unless $1 == "16" && $2 == "16"
  when /\ABITMAP/
    rows = []
  when /\AENDCHAR/
    glyphs[encoding] = rows if rows && rows.size == 16
    rows = nil
  when /\A([0-9A-Fa-f]{4})\s*\z/
    rows << $1.to_i(16) if rows
  end
end

entries = []  # [unicode, rows]
File.foreach(table) do |line|
  next if line.start_with?("#")
  _sjis, jis, unicode = line.split("\t")
  next unless jis && unicode
  rows = glyphs[jis.to_i(16)]
  next unless rows
  entries << [unicode.to_i(16), rows]
end
entries.sort_by! { |u, _| u }
abort "#{table}: duplicate code points" if entries.map(&:first).uniq.size != entries.size

File.open(dst, "w") do |f|
  f.puts "/* Generated by gems/picoruby-pocket/tools/jisfont2c.rb from #{File.basename(bdf)}. Do not edit. */"
  f.puts "#ifndef FONT_JIS16_H"
  f.puts "#define FONT_JIS16_H"
  f.puts "#include <stdint.h>"
  f.puts "#define FONT_JIS16_COUNT #{entries.size}"
  f.puts "/* Code points in ascending order; font_jis16_glyphs[i] draws font_jis16_codes[i]. */"
  f.puts "static const uint16_t font_jis16_codes[FONT_JIS16_COUNT] = {"
  entries.each_slice(12) do |slice|
    f.puts "  " + slice.map { |u, _| format("0x%04x", u) }.join(", ") + ","
  end
  f.puts "};"
  f.puts "static const uint8_t font_jis16_glyphs[FONT_JIS16_COUNT][32] = {"
  entries.each do |u, rows|
    bytes = rows.flat_map { |w| [(w >> 8) & 0xff, w & 0xff] }
    f.puts "  /* U+#{format('%04X', u)} */ { " + bytes.map { |b| format("0x%02x", b) }.join(",") + " },"
  end
  f.puts "};"
  f.puts "#endif"
end
puts "wrote #{dst}: #{entries.size} glyphs"
