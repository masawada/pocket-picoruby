#!/usr/bin/env ruby
# Convert a fixed-cell 8xN BDF font (ASCII 0x20..0x7E) into a C header.
#
#   ruby bdf2c.rb shnm8x16a.bdf font_8x16.h
#
# Every glyph must have the same BBX (true for the Shinonome ASCII fonts);
# each bitmap row is one byte, MSB = leftmost pixel.

FIRST = 0x20
LAST = 0x7e

src, dst = ARGV
abort "usage: bdf2c.rb <font.bdf> <out.h>" unless src && dst

glyphs = {}
height = nil
encoding = nil
rows = nil

File.foreach(src) do |line|
  case line
  when /\AENCODING (\d+)/
    encoding = $1.to_i
  when /\ABBX (\d+) (\d+) (-?\d+) (-?\d+)/
    w, h = $1.to_i, $2.to_i
    abort "#{src}: glyph #{encoding} is #{w}px wide; only 8px cells are supported" unless w == 8
    height ||= h
    abort "#{src}: glyph #{encoding} has height #{h}, expected #{height}" unless h == height
  when /\ABITMAP/
    rows = []
  when /\AENDCHAR/
    glyphs[encoding] = rows if encoding.between?(FIRST, LAST)
    rows = nil
  when /\A([0-9A-Fa-f]{2})\s*\z/
    rows << $1.to_i(16) if rows
  end
end

missing = (FIRST..LAST).reject { |c| glyphs[c] }
abort "#{src}: missing glyphs for #{missing.inspect}" unless missing.empty?

File.open(dst, "w") do |f|
  f.puts "/* Generated by firmware/tools/bdf2c.rb from #{File.basename(src)}. Do not edit. */"
  f.puts "#ifndef FONT_8X#{height}_H"
  f.puts "#define FONT_8X#{height}_H"
  f.puts "#include <stdint.h>"
  f.puts "#define FONT_WIDTH 8"
  f.puts "#define FONT_HEIGHT #{height}"
  f.puts "#define FONT_FIRST_CHAR 0x#{FIRST.to_s(16)}"
  f.puts "#define FONT_LAST_CHAR 0x#{LAST.to_s(16)}"
  f.puts "static const uint8_t font_glyphs[#{LAST - FIRST + 1}][FONT_HEIGHT] = {"
  (FIRST..LAST).each do |c|
    label = c == 0x5c ? "backslash" : c.chr
    f.puts "  /* 0x#{c.to_s(16)} #{label} */ { #{glyphs[c].map { |b| format('0x%02x', b) }.join(', ')} },"
  end
  f.puts "};"
  f.puts "#endif"
end
