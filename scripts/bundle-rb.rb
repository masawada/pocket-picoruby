#!/usr/bin/env ruby
# Join ruby/lib/tetris/*.rb and ruby/tetris_main.rb into build/tetris.rb.
# The device reads one .rb from its data slot and has no require for files
# on the SD card, so the game ships as a single script.
#
#   ruby scripts/bundle-rb.rb            # writes build/tetris.rb
#   ruby scripts/bundle-rb.rb out.rb     # writes elsewhere

ROOT = File.expand_path("..", __dir__)
out = ARGV[0] || File.join(ROOT, "build/tetris.rb")
parts = Dir[File.join(ROOT, "ruby/lib/tetris/*.rb")].sort + [File.join(ROOT, "ruby/tetris_main.rb")]

require "fileutils"
FileUtils.mkdir_p(File.dirname(out))
File.open(out, "w") do |f|
  f.puts "# Generated by scripts/bundle-rb.rb from:"
  parts.each { |p| f.puts "#   #{p.sub("#{ROOT}/", '')}" }
  parts.each do |p|
    f.puts
    f.puts "# ---- #{File.basename(p)} ----"
    f.write File.read(p)
  end
end
puts "wrote #{out} (#{File.size(out)} bytes)"
